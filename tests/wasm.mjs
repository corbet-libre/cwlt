import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import init,{prepare} from '../pkg/cwlt.js';
await init({module_or_path:await readFile(new URL('../pkg/cwlt_bg.wasm',import.meta.url))});
const r={old:{available:0,reserved:0,debt:0,accepted:1,declined:0,punished:0},action:8,capacity:3,amount:1,role:0,phase:3,outcome:1,kind:4,answered:true,selfPunished:false,changeCost:1,refillUnits:1};
const apply=value=>JSON.parse(prepare(JSON.stringify(value)));
const burn=apply(r);assert.equal(burn.balances.debt,1);assert.equal(burn.selfPunished,true);
const paid=apply({...r,old:burn.balances,action:6});assert.equal(paid.balances.debt,0);assert.equal(paid.balances.available,0);
const refill=apply({...r,old:paid.balances,action:6});assert.equal(refill.balances.available,1);
assert.throws(()=>apply({...r,old:burn.balances,phase:7,selfPunished:true}));
assert.throws(()=>prepare('{"private":"malformed"}'));
const original={...r,old:{available:1,reserved:2,debt:0,accepted:0,declined:0,punished:0},action:10,amount:2,phase:1,outcome:0,answered:false};
const early=apply(original);assert.equal(early.balances.available,2);assert.equal(early.balances.punished,1);
const next=(plan,kind)=>apply({...original,old:plan.balances,phase:plan.phase,outcome:plan.outcome,answered:plan.answered,kind});
const terminal=next(early,1);assert.deepEqual(terminal.balances,early.balances);assert.equal(terminal.phase,7);
assert.deepEqual(next(apply({...original,kind:1}),4).balances,terminal.balances);
console.log('Native-equivalent wasm punishment, debt, refill and replay vectors passed');
